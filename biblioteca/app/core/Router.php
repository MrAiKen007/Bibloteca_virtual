<?php

class Router
{
    /*
    |--------------------------------------------------------------------------
    | ARMAZENAR ROTAS
    |--------------------------------------------------------------------------
    */

    private $rotas = [];

    /*
    |--------------------------------------------------------------------------
    | REGISTAR ROTAS GET
    |--------------------------------------------------------------------------
    */

    public function get($url, $acao)
    {
        $this->rotas['GET'][$url] = $acao;
    }

    /*
    |--------------------------------------------------------------------------
    | REGISTAR ROTAS POST
    |--------------------------------------------------------------------------
    */

    public function post($url, $acao)
    {
        $this->rotas['POST'][$url] = $acao;
    }

    /*
    |--------------------------------------------------------------------------
    | EXECUTAR ROTA
    |--------------------------------------------------------------------------
    */

    public function executar($url, $metodo)
    {
        /*
        |--------------------------------------------------------------------------
        | VERIFICAR SE A ROTA EXISTE
        |--------------------------------------------------------------------------
        */

        if (!isset($this->rotas[$metodo][$url])) {

            echo "Rota não encontrada.";
            exit;
        }

        /*
        |--------------------------------------------------------------------------
        | OBTER AÇÃO
        |--------------------------------------------------------------------------
        */

        $acao = $this->rotas[$metodo][$url];

        $controlador = $acao[0];
        $metodoControlador = $acao[1];

        /*
        |--------------------------------------------------------------------------
        | VERIFICAR SE CONTROLADOR EXISTE
        |--------------------------------------------------------------------------
        */

       $caminhoControlador = __DIR__ . '/../controladores/' . $controlador . '.php';

        if (!file_exists($caminhoControlador)) 
        {

            echo $caminhoControlador;
            exit;
        }

        require_once $caminhoControlador;

        /*
        |--------------------------------------------------------------------------
        | INSTANCIAR CONTROLADOR
        |--------------------------------------------------------------------------
        */

        $instancia = new $controlador();

        /*
        |--------------------------------------------------------------------------
        | VERIFICAR MÉTODO
        |--------------------------------------------------------------------------
        */

        if (!method_exists($instancia, $metodoControlador)) {

            echo "Método do controlador não encontrado.";
            exit;
        }

        /*
        |--------------------------------------------------------------------------
        | EXECUTAR MÉTODO
        |--------------------------------------------------------------------------
        */

        call_user_func([
            $instancia,
            $metodoControlador
        ]);
    }
}